def test_audit_tamper_attempt_raises_engine_rejection():
    """Scenario 3: Audit tamper attempt (UPDATE/DELETE) raises engine-level error (IntegrityError/InsufficientPrivilege)."""
    import app.db as db
    from app.audit.logger import AuditLogger

    db.init_db()

    from app.decision.replay import DecisionStore
    DecisionStore().save({
        "decision_id": "dec_tamper_test_01",
        "case_id": "EVT-TAMPER-DRILL-01",
        "features": {},
        "chosen_action": "ESCALATE",
    })
    logger = AuditLogger()
    record = {
        "decision_id": "dec_tamper_test_01",
        "event_id": "EVT-TAMPER-DRILL-01",
        "case_id": "EVT-TAMPER-DRILL-01",
        "timestamp": "2026-08-29T12:00:00Z",
        "payload": {"status": "AUTHENTIC_RECORD"},
    }
    logger.log(record)

    # 1. Attempt UPDATE -> must raise IntegrityError from prevent_audit_update trigger
    with pytest.raises(Exception) as exc_update:
        with db.get_conn() as conn:
            conn.execute(
                "UPDATE audit_logs SET payload_json = ? WHERE event_id = ?",
                ('{"tampered": true}', "EVT-TAMPER-DRILL-01"),
            )
    assert "audit_log is append-only: UPDATE forbidden" in str(exc_update.value) or "permission denied" in str(exc_update.value)

    # 2. Attempt DELETE -> must raise IntegrityError from prevent_audit_delete trigger
    with pytest.raises(Exception) as exc_delete:
        with db.get_conn() as conn:
            conn.execute("DELETE FROM audit_logs WHERE event_id = ?", ("EVT-TAMPER-DRILL-01",))
    assert "audit_log is append-only: DELETE forbidden" in str(exc_delete.value) or "permission denied" in str(exc_delete.value)


def test_provider_down_circuit_breaker_short_circuits_and_logs_audit(monkeypatch):
    """Scenario 4: Gateway provider down trips circuit breaker, short-circuits further calls, routes safely to ESCALATE."""
    import json
    import app.db as db
    from app.pipeline import RecoveryPipeline
    from app.execution.simulator import SubscriptionSimulator
    from app.execution.live_executor import LiveExecutor
    from app.execution.razorpay import RazorpayAPIError
    from app.execution.circuit_breaker import CircuitBreaker, CircuitState

    db.init_db()

    class MockFailingAdapter:
        def __init__(self):
            self.call_count = 0
        def create_payment_link(self, *args, **kwargs):
            self.call_count += 1
            raise RazorpayAPIError("503 Service Unavailable: Gateway Switch Down")
        def fetch_payment_link(self, *args, **kwargs):
            self.call_count += 1
            raise RazorpayAPIError("503 Service Unavailable: Gateway Switch Down")

    mock_adapter = MockFailingAdapter()
    cb = CircuitBreaker(failure_threshold=3, recovery_timeout=60.0)
    pipeline = RecoveryPipeline(simulator=SubscriptionSimulator(42))
    pipeline.live_executor = LiveExecutor(adapter=mock_adapter)
    pipeline.circuit_breaker = cb

    cases = [
        {
            "event_id": f"EVT-CB-TEST-{i:02d}",
            "customer_name": f"Customer {i}",
            "amount": 2499.0,
            "subscription_status": "pending",
            "invoice_status": "issued",
            "payment_method_type": "international_card",
            "attempt_number": 2,
            "contact_count_7d": 1,
            "customer_opted_out": False,
            "native_retry_scheduled": False,
            "current_time": "2026-08-29T12:00:00+05:30",
            "is_live": True,
        }
        for i in range(1, 6)
    ]

    results = [pipeline.process(c, is_preview=False) for c in cases]

    # (a) Circuit Breaker transitioned to OPEN
    assert cb.state == CircuitState.OPEN

    # (b) External call count capped at 3 (requests 4 and 5 short-circuited)
    assert mock_adapter.call_count == 3

    # (c) Requests 4 & 5 routed safely without silent drops
    assert results[3]["chosen_action"] in ("ESCALATE", "WAIT")
    assert results[3]["execution_status"] == "BLOCKED_CIRCUIT_OPEN"
    assert results[4]["chosen_action"] in ("ESCALATE", "WAIT")
    assert results[4]["execution_status"] == "BLOCKED_CIRCUIT_OPEN"

    # (d) Audit rows exist for all 5 attempts
    with db.get_conn() as conn:
        for c in cases:
            count = conn.execute("SELECT COUNT(*) FROM audit_logs WHERE event_id = ?", (c["event_id"],)).fetchone()[0]
            assert count >= 1


def test_crash_between_authorization_and_razorpay_call_preserves_resumable_outbox_intent(monkeypatch):
    """
    Simulate a crash occurring immediately after authorization & transactional outbox persistence,
    BEFORE the outbound Razorpay network call.
    Verify that upon process restart/recovery, the pending intent is preserved in a valid, resumable state.
    """
    import app.db as db
    from app.pipeline import RecoveryPipeline
    from app.execution.simulator import SubscriptionSimulator
    from app.execution.outbox import get_pending_intents, claim_pending_intent, mark_intent_status

    db.init_db()

    case_id = f"EVT-CRASH-TEST-{int(time.time())}"
    case = {
        "event_id": case_id,
        "customer_name": "Crash Test Customer",
        "amount": 2499.0,
        "subscription_status": "pending",
        "invoice_status": "issued",
        "payment_method_type": "international_card",
        "attempt_number": 1,
        "contact_count_7d": 0,
        "customer_opted_out": False,
        "native_retry_scheduled": False,
        "current_time": "2026-08-29T12:00:00+05:30",
        "is_live": True,
    }

    # 1. Pipeline instance 1 crashes right as _execute_live is called
    pipe_pre_crash = RecoveryPipeline(simulator=SubscriptionSimulator(42))

    class SimulatedProcessCrash(Exception):
        pass

    def crash_before_external_call(*args, **kwargs):
        raise SimulatedProcessCrash("Simulated worker crash / SIGKILL immediately before outbound Razorpay call")

    monkeypatch.setattr("app.pipeline.claim_pending_intent", crash_before_external_call)

    with pytest.raises(SimulatedProcessCrash):
        pipe_pre_crash.process(case, is_preview=False)

    # 2. Worker restarts (new pipeline / worker process)
    # The outbox intent must be present in 'PENDING' state with durable authorization
    target_intents = get_pending_intents(case_id=case_id)
    assert len(target_intents) == 1
    intent = target_intents[0]
    assert intent["status"] == "PENDING"
    assert intent["action"] in ("MANUAL_RECOVERY", "NUDGE")

    # Assert decision record is durably present in decision_records
    with db.get_conn() as conn:
        dec_row = conn.execute("SELECT * FROM decision_records WHERE decision_id = ?", (intent["decision_id"],)).fetchone()
        assert dec_row is not None
        assert dec_row["case_id"] == case_id

    # 3. Resumed worker claims intent and finishes dispatch exactly once
    claimed = claim_pending_intent(intent["id"])
    assert claimed is not None
    assert claimed["status"] == "PROCESSING"

    # Worker calls Razorpay provider and stores response
    mark_intent_status(
        intent["id"],
        "EXECUTION_REQUESTED",
        {
            "status": "EXECUTION_REQUESTED",
            "payment_link_id": "plink_resumed_123",
            "payment_link_url": "https://rzp.io/rzp/resumed",
        },
    )

    with db.get_conn() as conn:
        final_intent = conn.execute("SELECT * FROM execution_intents WHERE id = ?", (intent["id"],)).fetchone()
        assert final_intent["status"] == "EXECUTION_REQUESTED"
        assert "plink_resumed_123" in str(final_intent["result_json"])
